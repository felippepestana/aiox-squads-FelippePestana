"""Generates brand/tokens.css and brand/tokens.json from the palette defined below.

Usage: python3 scripts/gen_tokens.py
"""
import json
from pathlib import Path

OUT = str(Path(__file__).resolve().parent.parent / "brand") + "/"

scale = {
  "indigo": {"50":"#EEF0FF","100":"#DDE1FF","200":"#C3C8FF","300":"#9A9CFF","400":"#7C7BF7","500":"#6360EC","600":"#5149DD","700":"#4338CA","800":"#362FA3","900":"#2A2680","950":"#1B1950"},
  "orange": {"100":"#FFE8D4","300":"#FFA24D","400":"#FF7A1A","500":"#FF6B00","700":"#B84700"},
  "neutral": {"0":"#FFFFFF","50":"#F6F7FB","100":"#ECEEF6","200":"#E3E6F0","300":"#C9CFE0","400":"#8A93B2","500":"#6B7599","600":"#4B5470","700":"#333B55","800":"#1C2238","900":"#0B1020","950":"#070A14"},
}
light = dict(bg="#F6F7FB",surface="#FFFFFF",surface_2="#ECEEF6",fg="#0B1020",fg_2="#4B5470",line="#E3E6F0",line_strong="#C9CFE0",
  primary="#4338CA",on_primary="#FFFFFF",primary_soft="#EEF0FF",accent="#FF6B00",on_accent="#0B1020",accent_text="#B84700",
  ok="#0E7C3A",ok_bg="#E6F6EC",warn="#9A5B00",warn_bg="#FFF4DB",bad="#C4271B",bad_bg="#FDECEA",info="#1D5FD1",info_bg="#E8F0FD",
  focus="#4338CA",logo="#4338CA",logo_dot="#FF6B00")
dark = dict(bg="#070A14",surface="#0F1426",surface_2="#151B33",fg="#EDEFF7",fg_2="#A9B0CC",line="#232A44",line_strong="#343C5C",
  primary="#9A9CFF",on_primary="#070A14",primary_soft="#1B1F45",accent="#FF7A1A",on_accent="#070A14",accent_text="#FFA24D",
  ok="#3DD68C",ok_bg="#0E2A1E",warn="#FBBF24",warn_bg="#2B2208",bad="#FF8A80",bad_bg="#2E1513",info="#7FB2FF",info_bg="#0F1F3A",
  focus="#9A9CFF",logo="#FFFFFF",logo_dot="#FF7A1A")
assert light.keys() == dark.keys()
kebab = lambda k: k.replace("_", "-")

type_ = {
  "font-display": "'Sora', system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
  "font-body": "'Inter', system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
  "font-mono": "'JetBrains Mono', ui-monospace, SFMono-Regular, Menlo, Consolas, monospace",
}
sizes = {"display": ("clamp(2.5rem, 5vw + 1rem, 4rem)", "1.05", "700"), "h1": ("clamp(2rem, 3vw + 1rem, 2.75rem)", "1.1", "700"),
         "h2": ("1.75rem", "1.2", "700"), "h3": ("1.25rem", "1.3", "600"), "body-lg": ("1.125rem", "1.6", "400"),
         "body": ("1rem", "1.6", "400"), "small": ("0.875rem", "1.5", "400"), "caption": ("0.75rem", "1.4", "500"),
         "overline": ("0.75rem", "1.3", "500"), "data": ("1rem", "1.3", "500")}
space = {"0":"0","1":"4px","2":"8px","3":"12px","4":"16px","5":"20px","6":"24px","8":"32px","10":"40px","12":"48px","16":"64px","20":"80px"}
radius = {"sm":"8px","md":"12px","lg":"16px","xl":"24px","full":"999px"}
shadow = {"sm":"0 1px 2px rgb(11 16 32 / 0.08)","md":"0 4px 12px rgb(11 16 32 / 0.10)","lg":"0 12px 32px rgb(11 16 32 / 0.14)"}
motion = {"duration-fast":"120ms","duration-base":"200ms","duration-slow":"320ms","ease-rise":"cubic-bezier(0.2, 0.8, 0.2, 1)"}

def block(d, indent="  "):
    return "\n".join(f"{indent}--apx-{kebab(k)}: {v};" for k, v in d.items())

css = ["/* APEX Plataforma de Cursos Livres - design tokens (generated by brand tooling; do not edit by hand).",
       "   Light is the default; dark follows the OS unless data-theme is set. Contrast of every text/background",
       "   pair is verified >= 4.5:1 (see docs/apex-cursos-livres/15-identidade-visual-apex.md). */",
       ":root {"]
for fam, steps in scale.items():
    for step, hexv in steps.items():
        css.append(f"  --apx-{fam}-{step}: {hexv};")
css.append(block(light))
for k, v in type_.items(): css.append(f"  --apx-{k}: {v};")
for k, (size, lh, w) in sizes.items():
    css += [f"  --apx-text-{k}-size: {size};", f"  --apx-text-{k}-line: {lh};", f"  --apx-text-{k}-weight: {w};"]
for k, v in space.items(): css.append(f"  --apx-space-{k}: {v};")
for k, v in radius.items(): css.append(f"  --apx-radius-{k}: {v};")
for k, v in shadow.items(): css.append(f"  --apx-shadow-{k}: {v};")
for k, v in motion.items(): css.append(f"  --apx-{k}: {v};")
css.append("  --apx-focus-ring: 0 0 0 2px var(--apx-bg), 0 0 0 4px var(--apx-focus);")
css.append("}")
css += ["", "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {", block(dark, "    "), "    color-scheme: dark;", "  }", "}",
        "", ":root[data-theme=\"dark\"] {", block(dark), "  color-scheme: dark;", "}", "",
        "@media (prefers-reduced-motion: reduce) {", "  :root { --apx-duration-fast: 0ms; --apx-duration-base: 0ms; --apx-duration-slow: 0ms; }", "}", ""]
open(OUT + "tokens.css", "w", encoding="utf-8").write("\n".join(css))

def tok(v, t="color"): return {"$value": v, "$type": t}
j = {"$description": "APEX Plataforma de Cursos Livres design tokens (W3C DTCG style). Generated; do not edit by hand.",
     "color": {fam: {s: tok(h) for s, h in steps.items()} for fam, steps in scale.items()},
     "theme": {"light": {k: tok(v) for k, v in light.items()}, "dark": {k: tok(v) for k, v in dark.items()}},
     "font": {"display": tok(type_["font-display"], "fontFamily"), "body": tok(type_["font-body"], "fontFamily"), "mono": tok(type_["font-mono"], "fontFamily")},
     "text": {k: {"size": tok(s, "dimension"), "lineHeight": tok(lh, "number"), "weight": tok(w, "fontWeight")} for k, (s, lh, w) in sizes.items()},
     "space": {k: tok(v, "dimension") for k, v in space.items()},
     "radius": {k: tok(v, "dimension") for k, v in radius.items()},
     "shadow": {k: tok(v, "shadow") for k, v in shadow.items()},
     "motion": {k: tok(v, "duration" if k.startswith("duration") else "cubicBezier") for k, v in motion.items()}}
open(OUT + "tokens.json", "w", encoding="utf-8").write(json.dumps(j, indent=2, ensure_ascii=False) + "\n")

# Consistency checks: every JSON color appears in CSS and vice versa.
css_text = "\n".join(css).lower()
for theme in ("light", "dark"):
    for k, v in j["theme"][theme].items():
        assert v["$value"].lower() in css_text, (theme, k)
print("tokens.css lines:", len(css), "| tokens.json keys:", list(j.keys()))
